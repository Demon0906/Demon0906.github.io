function renderModelNavigation() {
  if (!modelMenu) return;
  const modelGroups = (window.portraitCollections || [])
    .flatMap((collection) =>
      (collection.groups || []).map((group) => ({
        collection: collection.collection,
        id: group.id,
        title: group.title,
      })),
    )
    .filter((group, index, groups) => groups.findIndex((item) => item.title === group.title) === index)
    .sort((a, b) => a.title.localeCompare(b.title, "zh-Hans-CN", { numeric: true, sensitivity: "base" }));

  if (!modelGroups.length) return;
  modelMenu.innerHTML = modelGroups
    .map(
      (group) => `
        <a href="portrait.html?collection=${encodeURIComponent(group.collection)}#${encodeURIComponent(group.id)}">
          ${escapeHtml(group.title)}
        </a>
      `,
    )
    .join("");
}

function renderPortfolio() {
  const coldGalleryOrder = ["portrait", "nature", "city", "architecture", "daily"];
  const workSections = portfolioSections
    .filter((section) => !isStorySection(section))
    .sort((a, b) => coldGalleryOrder.indexOf(a.id) - coldGalleryOrder.indexOf(b.id));
  const storySection = portfolioSections.find(isStorySection);
  renderPortfolioNavigation();
  renderModelNavigation();
  portfolioMount.innerHTML = workSections.map(renderSection).join("");
  if (storyMount && storySection) {
    storyMount.innerHTML = renderStoryBook(storySection);
  }
  initCoverAutoScroll();
  initStoryBookPaging();
}

function initCoverAutoScroll() {
  document.querySelectorAll(".project-cover-stack").forEach((stack) => {
    if (stack.dataset.autoReady === "true" || stack.children.length < 2) return;
    stack.dataset.autoReady = "true";
    let index = 0;
    const updateBackground = () => {
      const activeImage = stack.children[index];
      const card = stack.closest(".project-card, .series-card");
      if (!activeImage || !card) return;
      card.style.setProperty("--cover-bg", `url("${activeImage.currentSrc || activeImage.src}")`);
    };
    updateBackground();
    let scrollTimer;
    stack.addEventListener(
      "scroll",
      () => {
        window.clearTimeout(scrollTimer);
        scrollTimer = window.setTimeout(() => {
          index = Math.max(0, Math.min(stack.children.length - 1, Math.round(stack.scrollLeft / stack.clientWidth)));
          updateBackground();
        }, 90);
      },
      { passive: true },
    );
    setInterval(() => {
      if (stack.matches(":hover")) return;
      index = (index + 1) % stack.children.length;
      updateBackground();
      stack.scrollTo({ left: stack.clientWidth * index, behavior: "smooth" });
    }, 3600);
  });
}

function initStoryBookPaging() {
  const storyBook = document.querySelector(".story-book");
  const pages = [...(storyBook?.querySelectorAll(".story-book-card") || [])];
  if (!storyBook || !pages.length || storyBook.dataset.pagingReady === "true") return;
  storyBook.dataset.pagingReady = "true";
  let activeIndex = 0;
  let isTurning = false;
  const updatePages = () => {
    pages.forEach((page, index) => {
      page.classList.toggle("is-active", index === activeIndex);
      page.classList.toggle("is-before", index < activeIndex);
      page.classList.toggle("is-after", index > activeIndex);
      page.setAttribute("aria-hidden", index === activeIndex ? "false" : "true");
    });
  };
  const setPage = (nextIndex, direction = "next") => {
    if (isTurning || nextIndex === activeIndex) return;
    isTurning = true;
    storyBook.classList.remove("is-turning-next", "is-turning-prev");
    storyBook.classList.add(direction === "prev" ? "is-turning-prev" : "is-turning-next");
    window.setTimeout(() => {
      activeIndex = (nextIndex + pages.length) % pages.length;
      updatePages();
    }, 360);
    window.setTimeout(() => {
      storyBook.classList.remove("is-turning-next", "is-turning-prev");
      isTurning = false;
    }, 920);
  };
  updatePages();
  storyBook.querySelectorAll(".story-book-turn").forEach((button) => {
    button.addEventListener("click", (event) => {
      event.preventDefault();
      event.stopPropagation();
      const direction = button.classList.contains("story-book-prev") ? -1 : 1;
      setPage(activeIndex + direction, direction < 0 ? "prev" : "next");
    });
  });
}

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : language === "ja" ? "ja" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });
  renderPortfolio();
}

function openLightbox(sectionId, projectId, photoIndex) {
  const project = getProject(sectionId, projectId);
  const index = Number(photoIndex);
  const src = project?.photos[index];
  if (!project || !src) return;
  const photoInfo = window.photoInfoFromPath?.(src);
  lightboxState = { sectionId, projectId, photoIndex: index };
  lightboxImage.src = window.localImage ? window.localImage(src) : src;
  lightboxImage.alt = localized(project.title);
  lightboxTitle.textContent = photoInfo?.title || localized(project.title);
  lightboxMeta.textContent = photoInfo?.meta || `${project.date} / ${localized(project.place)}`;
  if (!lightbox.open) lightbox.showModal();
  requestAnimationFrame(() => {
    lightbox.scrollTop = 0;
    lightbox.scrollLeft = 0;
  });
}

function moveLightbox(direction) {
  const project = getProject(lightboxState.sectionId, lightboxState.projectId);
  if (!project?.photos?.length) return;
  const nextIndex = (lightboxState.photoIndex + direction + project.photos.length) % project.photos.length;
  openLightbox(lightboxState.sectionId, lightboxState.projectId, nextIndex);
}

