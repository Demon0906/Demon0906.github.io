const languageButtons = document.querySelectorAll(".language-button");
const portfolioMount = document.querySelector("#portfolio-groups");
const lightbox = document.querySelector("#lightbox");
const lightboxImage = document.querySelector("#lightbox-image");
const lightboxTitle = document.querySelector("#lightbox-title");
const lightboxMeta = document.querySelector("#lightbox-meta");
const lightboxClose = document.querySelector(".lightbox-close");
const bookingForm = document.querySelector("#booking-form");
const privacyToast = document.querySelector("#privacy-toast");
const activeCategories = {};
let currentLanguage = "zh";
let toastTimer;

function t(key) {
  return translations[currentLanguage][key] || translations.zh[key] || key;
}

function localized(value) {
  if (typeof value === "string") return value;
  return value[currentLanguage] || value.zh;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function getCategory(groupId, categoryId) {
  return portfolioGroups.find((group) => group.id === groupId)?.categories.find((category) => category.id === categoryId);
}

function renderCategoryCard(group, category, includeAnchor = false) {
  return `
    <button class="category-card ${activeCategories[group.id] === category.id ? "is-active" : ""}" type="button" data-group="${group.id}" data-category="${category.id}" ${includeAnchor ? `id="${category.id}"` : ""}>
      <img class="protected-media" src="${category.cover}" alt="${escapeHtml(localized(category.title))}" loading="lazy" draggable="false">
      <span class="category-overlay">
        <span>${t(category.labelKey)}</span>
        <strong>${localized(category.title)}</strong>
        <em>${t("viewSets")}</em>
      </span>
    </button>
  `;
}

function renderGroup(group) {
  activeCategories[group.id] ||= group.categories[0].id;
  const primaryCards = group.categories.map((category) => renderCategoryCard(group, category, true)).join("");
  const duplicateCards = group.categories.map((category) => renderCategoryCard(group, category)).join("");
  const trackCards = primaryCards + duplicateCards;

  return `
    <section class="portfolio-group" id="${group.anchor}" aria-labelledby="${group.id}-title">
      <div class="group-heading">
        <div>
          <p class="eyebrow">${group.id === "camera" ? "Camera Photography" : "Mobile Photography"}</p>
          <h3 id="${group.id}-title">${t(group.titleKey)}</h3>
        </div>
        <p>${t(group.introKey)}</p>
      </div>
      <div class="auto-rail" aria-label="${escapeHtml(t(group.titleKey))}">
        <div class="auto-track">${trackCards}</div>
      </div>
      <div class="set-detail" id="${group.id}-detail"></div>
    </section>
  `;
}

function renderSetDetail(group) {
  const category = getCategory(group.id, activeCategories[group.id]);
  const mount = document.querySelector(`#${group.id}-detail`);
  if (!category || !mount) return;

  mount.innerHTML = `
    <div class="detail-heading">
      <div>
        <p class="eyebrow">${t(category.labelKey)}</p>
        <h4>${localized(category.title)}</h4>
      </div>
      <span>${category.sets.length} ${t("setLabel")}</span>
    </div>
    <div class="photo-sets">
      ${category.sets
        .map(
          (set, setIndex) => `
            <article class="photo-set">
              <header>
                <div>
                  <p>${t("dateLabel")} / ${set.date}</p>
                  <h5>${localized(set.title)}</h5>
                </div>
                <span>${t("locationLabel")} / ${localized(set.place)}</span>
              </header>
              <div class="photo-strip">
                ${set.photos
                  .map(
                    (src, photoIndex) => `
                      <button class="set-photo" type="button" data-group="${group.id}" data-category="${category.id}" data-set="${setIndex}" data-photo="${photoIndex}">
                        <img class="protected-media" src="${src}" alt="${escapeHtml(localized(set.title))}" loading="lazy" draggable="false">
                      </button>
                    `,
                  )
                  .join("")}
              </div>
            </article>
          `,
        )
        .join("")}
    </div>
  `;
}

function renderPortfolio() {
  portfolioMount.innerHTML = portfolioGroups.map(renderGroup).join("");
  portfolioGroups.forEach(renderSetDetail);
}

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : language === "ja" ? "ja" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
  });
  renderPortfolio();
}

function openLightbox(groupId, categoryId, setIndex, photoIndex) {
  const category = getCategory(groupId, categoryId);
  const set = category?.sets[Number(setIndex)];
  const src = set?.photos[Number(photoIndex)];
  if (!category || !set || !src) return;

  lightboxImage.src = src;
  lightboxImage.alt = localized(set.title);
  lightboxTitle.textContent = localized(set.title);
  lightboxMeta.textContent = `${t(category.labelKey)} / ${set.date} / ${localized(set.place)}`;
  lightbox.showModal();
}

function showPrivacyToast() {
  privacyToast.classList.add("is-visible");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => privacyToast.classList.remove("is-visible"), 2600);
}

function buildMailto(formData) {
  const lines = [
    t("mailBodyTitle"),
    "",
    `${t("formName")}: ${formData.get("name")}`,
    `${t("formContact")}: ${formData.get("contact")}`,
    `${t("formDate")}: ${formData.get("date")}`,
    `${t("formContent")}:`,
    formData.get("content"),
  ];

  return `mailto:${contactEmail}?subject=${encodeURIComponent(t("mailSubject"))}&body=${encodeURIComponent(lines.join("\n"))}`;
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

document.addEventListener("click", (event) => {
  const categoryCard = event.target.closest(".category-card");
  if (categoryCard) {
    activeCategories[categoryCard.dataset.group] = categoryCard.dataset.category;
    renderPortfolio();
    document.querySelector(`#${categoryCard.dataset.group}-detail`)?.scrollIntoView({ behavior: "smooth", block: "start" });
    return;
  }

  const photo = event.target.closest(".set-photo");
  if (photo) {
    openLightbox(photo.dataset.group, photo.dataset.category, photo.dataset.set, photo.dataset.photo);
  }
});

document.addEventListener("contextmenu", (event) => {
  if (event.target.closest(".protected-media, .photo-set, .category-card, .lightbox")) {
    event.preventDefault();
    showPrivacyToast();
  }
});

document.addEventListener("dragstart", (event) => {
  if (event.target.closest(".protected-media")) {
    event.preventDefault();
    showPrivacyToast();
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "PrintScreen") {
    showPrivacyToast();
  }
});

bookingForm.addEventListener("submit", (event) => {
  event.preventDefault();
  if (!bookingForm.reportValidity()) return;

  window.location.href = buildMailto(new FormData(bookingForm));
});

lightboxClose.addEventListener("click", () => lightbox.close());

lightbox.addEventListener("click", (event) => {
  if (event.target === lightbox) {
    lightbox.close();
  }
});

applyLanguage(currentLanguage);
